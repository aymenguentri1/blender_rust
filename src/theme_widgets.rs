#[cfg(test)]
mod tests {
    use super::*;

    fn check(w: WidgetColors, hex: [u32; 6], roundness: f32) {
        let got = [w.outline, w.inner, w.inner_sel, w.item, w.text, w.text_sel];
        assert_eq!(got, hex.map(u32::to_be_bytes));
        assert_eq!((w.shaded, w.shadetop, w.shadedown, w.roundness), (0, 0, 0, roundness));
    }

    /// outline, inner, inner_sel, item, text, text_sel as written in the C file.
    #[test]
    fn values_match_the_c_file() {
        check(WCOL_TOOL, [0x3d3d3dff, 0x545454ff, 0x4772b3ff, 0xffffffff, 0xe6e6e6ff, 0xffffffff], 0.2);
        check(WCOL_TOGGLE, [0x3d3d3dff, 0x545454ff, 0x4772b3ff, 0x252525ff, 0xe6e6e6ff, 0xffffffff], 0.2);
        check(WCOL_NUM, [0x3d3d3dff, 0x545454ff, 0x222222ff, 0x4772b3ff, 0xe6e6e6ff, 0xffffffff], 0.2);
        check(WCOL_MENU_ITEM, [0x3d3d3d00, 0x18181800, 0x4772b3ff, 0xffffff8f, 0xddddddff, 0xffffffff], 0.2);
        assert_eq!(WCOL_SCROLL.roundness, 0.5);
        assert_eq!((WCOL_STATE.inner_key_sel, WCOL_STATE.blend), (0xb29700ffu32.to_be_bytes(), 0.5));
    }
}
